import streamlit as st
import numpy as np
import pandas as pd
import pickle
from pathlib import Path
from fpdf import FPDF
import matplotlib.pyplot as plt
import io
import tempfile


# ============================================================
# PAGE CONFIGURATION
# ============================================================

st.set_page_config(
    page_title="Diabetes Prediction",
    page_icon="🩺",
    layout="centered"
)


# ============================================================
# PROJECT PATH
# ============================================================

BASE_DIR = Path(__file__).resolve().parent

MODEL_PATH = BASE_DIR / "Diabetes_Prediction_Model.pkl"
SCALER_PATH = BASE_DIR / "Diabetes_Prediction_Scaler.pkl"


# ============================================================
# LOAD MODEL AND SCALER
# ============================================================

@st.cache_resource
def load_model_and_scaler():

    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Model file not found:\n{MODEL_PATH}"
        )

    if not SCALER_PATH.exists():
        raise FileNotFoundError(
            f"Scaler file not found:\n{SCALER_PATH}"
        )

    with open(MODEL_PATH, "rb") as model_file:
        model = pickle.load(model_file)

    with open(SCALER_PATH, "rb") as scaler_file:
        scaler = pickle.load(scaler_file)

    return model, scaler


try:
    model, scaler = load_model_and_scaler()

except Exception as e:

    st.error("Unable to load the trained model or scaler.")

    st.code(str(e))

    st.stop()


# ============================================================
# PDF REPORT
# ============================================================

def generate_pdf(
    name,
    gender,
    age,
    hypertension,
    heart_disease,
    smoking_history,
    bmi,
    hba1c,
    glucose,
    result,
    probability
):

    pdf = FPDF()

    pdf.add_page()

    pdf.set_font("Arial", "B", 18)

    pdf.cell(
        0,
        12,
        "Diabetes Prediction Report",
        ln=True,
        align="C"
    )

    pdf.ln(8)

    pdf.set_font("Arial", "B", 13)

    pdf.cell(
        0,
        10,
        f"Medical Report for {name}",
        ln=True
    )

    pdf.ln(5)

    report_data = [

        ("Patient Name", name),

        ("Gender", gender),

        ("Age", age),

        ("Hypertension", hypertension),

        ("Heart Disease", heart_disease),

        ("Smoking History", smoking_history),

        ("BMI", f"{bmi:.1f}"),

        ("HbA1c Level", f"{hba1c:.1f}"),

        ("Blood Glucose Level", glucose),

        ("Prediction", result),

        ("Diabetes Probability", f"{probability:.2f}%")

    ]

    pdf.set_font("Arial", size=12)

    for key, value in report_data:

        pdf.cell(
            0,
            9,
            f"{key}: {value}",
            ln=True
        )

    pdf.ln(8)

    pdf.set_font("Arial", "I", 10)

    pdf.multi_cell(
        0,
        7,
        "This report is generated by a machine-learning "
        "prediction system and is not a medical diagnosis. "
        "Please consult a qualified healthcare professional "
        "for medical advice."
    )

    temp_file = tempfile.NamedTemporaryFile(
        delete=False,
        suffix=".pdf"
    )

    temp_file.close()

    pdf.output(temp_file.name)

    with open(temp_file.name, "rb") as file:

        pdf_data = file.read()

    Path(temp_file.name).unlink(missing_ok=True)

    return pdf_data


# ============================================================
# IMAGE REPORT
# ============================================================

def generate_image(
    name,
    gender,
    age,
    hypertension,
    heart_disease,
    smoking_history,
    bmi,
    hba1c,
    glucose,
    result,
    probability
):

    fig, ax = plt.subplots(
        figsize=(9, 7)
    )

    ax.axis("off")

    report = (

        "DIABETES PREDICTION REPORT\n\n"

        f"Patient Name: {name}\n"

        f"Gender: {gender}\n"

        f"Age: {age}\n"

        f"Hypertension: {hypertension}\n"

        f"Heart Disease: {heart_disease}\n"

        f"Smoking History: {smoking_history}\n"

        f"BMI: {bmi:.1f}\n"

        f"HbA1c Level: {hba1c:.1f}\n"

        f"Blood Glucose Level: {glucose}\n\n"

        f"Prediction: {result}\n"

        f"Diabetes Probability: {probability:.2f}%"

    )

    ax.text(

        0.5,
        0.90,
        report,

        fontsize=13,

        ha="center",
        va="top",

        linespacing=1.6
    )

    ax.text(

        0.5,
        0.08,

        "This prediction is not a medical diagnosis.",

        fontsize=10,

        ha="center"
    )

    plt.tight_layout()

    img_buffer = io.BytesIO()

    plt.savefig(

        img_buffer,

        format="png",

        dpi=150,

        bbox_inches="tight"
    )

    plt.close(fig)

    img_buffer.seek(0)

    return img_buffer.getvalue()


# ============================================================
# APPLICATION
# ============================================================

def main():

    st.title("🩺 Diabetes Prediction App")

    st.write(
        "Enter the patient's information below to generate "
        "a machine-learning based diabetes prediction."
    )

    st.divider()


    # ========================================================
    # PATIENT INFORMATION
    # ========================================================

    name = st.text_input(
        "Patient Name",
        placeholder="Enter patient name"
    )


    col1, col2 = st.columns(2)


    with col1:

        gender = st.selectbox(
            "Gender",
            ["Female", "Male"]
        )


        age = st.number_input(
            "Age",
            min_value=1,
            max_value=120,
            value=30,
            step=1
        )


        hypertension = st.selectbox(
            "Hypertension",
            ["No", "Yes"]
        )


        heart_disease = st.selectbox(
            "Heart Disease",
            ["No", "Yes"]
        )


    with col2:

        smoking_history = st.selectbox(

            "Smoking History",

            [
                "never",
                "current",
                "formerly",
                "No Info",
                "ever",
                "not current"
            ]
        )


        bmi = st.number_input(

            "BMI",

            min_value=10.0,

            max_value=100.0,

            value=25.0,

            step=0.1
        )


        hba1c = st.number_input(

            "HbA1c Level",

            min_value=3.0,

            max_value=15.0,

            value=5.5,

            step=0.1
        )


        glucose = st.number_input(

            "Blood Glucose Level",

            min_value=40,

            max_value=500,

            value=140,

            step=1
        )


    st.divider()


    # ========================================================
    # PREDICTION
    # ========================================================

    if st.button(
        "🔍 Predict Diabetes",
        type="primary",
        use_container_width=True
    ):

        if not name.strip():

            st.warning(
                "Please enter the patient's name."
            )

            st.stop()


        # ====================================================
        # ENCODING
        # ====================================================

        gender_mapping = {

            "Female": 0,

            "Male": 1
        }


        smoking_mapping = {

            "No Info": 0,

            "current": 1,

            "ever": 2,

            "formerly": 3,

            "never": 4,

            "not current": 5
        }


        gender_numeric = gender_mapping[gender]

        smoking_numeric = smoking_mapping[
            smoking_history
        ]


        hypertension_numeric = (

            1 if hypertension == "Yes"

            else 0
        )


        heart_disease_numeric = (

            1 if heart_disease == "Yes"

            else 0
        )


        # ====================================================
        # CREATE FEATURE DATA
        # ====================================================

        feature_data = pd.DataFrame(

            [[

                gender_numeric,

                age,

                hypertension_numeric,

                heart_disease_numeric,

                smoking_numeric,

                bmi,

                hba1c,

                glucose

            ]],

            columns=[

                "gender",

                "age",

                "hypertension",

                "heart_disease",

                "smoking_history",

                "bmi",

                "HbA1c_level",

                "blood_glucose_level"

            ]
        )


        # ====================================================
        # SCALE FEATURES
        # ====================================================

        scaled_features = scaler.transform(
            feature_data
        )


        # ====================================================
        # PREDICTION
        # ====================================================

        prediction = model.predict(
            scaled_features
        )[0]


        # ====================================================
        # PROBABILITY
        # ====================================================

        if hasattr(model, "predict_proba"):

            probability = (

                model.predict_proba(
                    scaled_features
                )[0][1]

                * 100
            )

        else:

            probability = (

                100.0

                if prediction == 1

                else 0.0
            )


        result = (

            "Diabetic"

            if prediction == 1

            else "Non-Diabetic"
        )


        # ====================================================
        # DISPLAY REPORT
        # ====================================================

        st.subheader(
            "📋 Medical Report"
        )


        report_col1, report_col2 = st.columns(2)


        with report_col1:

            st.write(
                f"**Patient Name:** {name}"
            )

            st.write(
                f"**Gender:** {gender}"
            )

            st.write(
                f"**Age:** {age}"
            )

            st.write(
                f"**Hypertension:** {hypertension}"
            )

            st.write(
                f"**Heart Disease:** {heart_disease}"
            )


        with report_col2:

            st.write(
                f"**Smoking History:** "
                f"{smoking_history}"
            )

            st.write(
                f"**BMI:** {bmi:.1f}"
            )

            st.write(
                f"**HbA1c Level:** {hba1c:.1f}"
            )

            st.write(
                f"**Blood Glucose:** {glucose}"
            )


        st.divider()


        # ====================================================
        # RESULT
        # ====================================================

        if result == "Diabetic":

            st.error(

                f"### Prediction: {result}\n\n"

                f"Estimated probability: "
                f"{probability:.2f}%"
            )

            st.warning(

                "Please consult a qualified healthcare "
                "professional for proper evaluation."
            )

        else:

            st.success(

                f"### Prediction: {result}\n\n"

                f"Estimated probability: "
                f"{probability:.2f}%"
            )

            st.info(

                "Continue maintaining healthy lifestyle "
                "habits and consult a healthcare "
                "professional when appropriate."
            )


        # ====================================================
        # GENERATE REPORTS
        # ====================================================

        pdf_data = generate_pdf(

            name,

            gender,

            age,

            hypertension,

            heart_disease,

            smoking_history,

            bmi,

            hba1c,

            glucose,

            result,

            probability
        )


        image_data = generate_image(

            name,

            gender,

            age,

            hypertension,

            heart_disease,

            smoking_history,

            bmi,

            hba1c,

            glucose,

            result,

            probability
        )


        # ====================================================
        # DOWNLOAD BUTTONS
        # ====================================================

        st.divider()

        st.subheader(
            "📥 Download Report"
        )


        download_col1, download_col2 = st.columns(2)


        with download_col1:

            st.download_button(

                label="📄 Download PDF",

                data=pdf_data,

                file_name=(
                    "Diabetes_Medical_Report.pdf"
                ),

                mime="application/pdf",

                use_container_width=True
            )


        with download_col2:

            st.download_button(

                label="🖼️ Download PNG",

                data=image_data,

                file_name=(
                    "Diabetes_Medical_Report.png"
                ),

                mime="image/png",

                use_container_width=True
            )


    st.divider()


    st.caption(

        "⚠️ This application provides an ML-based "
        "prediction for educational purposes and is "
        "not a medical diagnosis."
    )


# ============================================================
# RUN APPLICATION
# ============================================================

if __name__ == "__main__":

    main()